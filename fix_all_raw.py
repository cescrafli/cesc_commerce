import re

with open('lib/main.dart', 'rb') as f:
    raw = f.read()

# Define the corrupted bullet sequence
corrupted_bullet = b'\xc3\x83\xc2\xa2\xc3\xa2\xe2\x80\x9a\xc2\xac\xc3\x82\xc2\xa2'
real_bullet = b'\xe2\x80\xa2'

# 12 bullets
raw = raw.replace(corrupted_bullet * 12, b'****')
# 4 bullets
raw = raw.replace(corrupted_bullet * 4, b'****')
# 3 bullets
raw = raw.replace(corrupted_bullet * 3, b'***')
# 1 bullet
raw = raw.replace(corrupted_bullet, real_bullet)

# Now, any remaining sequence that starts with \xc3\x83 and isn't valid should be wiped.
# Let's wipe the specific ones we found.
to_wipe = [
    b'\xc3\x83\xc2\xa2\xc3\xa2\xe2\x82\xac\xc2\xa0\xc3\x82\xc2\x90',
    b'\xc3\x83\xc2\xa2\xc3\xa2\xe2\x80\x9a\xc2\xac\xc3\xa2\xe2\x82\xac\xc2\x9d',
    b'\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\x85\xe2\x80\x99\xc3\x82\xc2\x90',
    b'\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\xa2\xe2\x82\xac\xc2\xa1\xc3\x82\xc2\xba\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\xa2\xe2\x82\xac\xc2\xa1\xc3\x82\xc2\xb8',
    b'\xc3\x83\xc2\xa2\xc3\xa2\xe2\x82\xac\xc2\xa0\xc3\xa2\xe2\x82\xac\xe2\x84\xa2',
    b'\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\xa2\xe2\x82\xac\xc2\x9d\xc3\x82\xc2\xa5',
    b'\xc3\xaf\xc2\xbf\xc2\xbd',
    b'\xc3\x83\xc2\xaf\xc3\x82\xc2\xbf\xc3\x82\xc2\xbd',
    b'\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\x85\xc2\xa1\xc3\x85\xc2\xa1',
    b'\xc3\x83\xc2\xb0\xc3\x85\xc2\xb8\xc3\xa2\xe2\x82\xac\xc2\xba\xc3\x82\xc2\xb5'
]

for w in to_wipe:
    raw = raw.replace(w, b'')

with open('lib/main.dart', 'wb') as f:
    f.write(raw)

print("All raw corrupted sequences replaced!")
